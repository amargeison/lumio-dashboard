// ─── 3. Bid narrative (copyable) ────────────────────────────────────────────
function bidNarrative(ctx: ImpactPortalContext) {
  const b = ctx.brand
  const paras = ctx.copy.funder.bidParas.map(p => fill(p, b))
  const body = `
    ${brandHeader(ctx, 'BID NARRATIVE · DRAFT')}
    <h1>AI-drafted bid narrative</h1>
    <div class="sub">Drop-in copy for grant applications and partner proposals — edit to fit the funder's word limit and priorities</div>
    ${paras.map(p => `<p style="margin-bottom:12px">${esc(p)}</p>`).join('')}
    <div class="foot">${esc(b.legal)} · ${foot(ctx)} · Use the Copy text button above to paste into a bid</div>
  `
  return shell(ctx, `${b.org} — Bid Narrative`, body, paras.join('\n\n'))
}

