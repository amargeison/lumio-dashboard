'use client'

// Live funder outputs — opens a print-ready branded document in a new tab.
// Built client-side from demo data; the production version renders the same
// templates from real registers/surveys (tp_funder_reports stores snapshots).

import { fill, type ImpactPortalContext } from '../_components/ImpactDataContext'

export type FunderDocKind = 'term-report' | 'funder-pack' | 'bid-narrative' | 'governor-pack' | 'newsletter-snippet'

const RED = '#D7262C'
const DARK = '#1B1B21'

export function esc(s: string) {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
}

// Footer credit — live documents draw from real registers, so no demo note.
export function foot(ctx: ImpactPortalContext, demoNote = ' (demo data — live version draws from real registers)') {
  return `Generated by the ${ctx.brand.portal}${ctx.mode === 'live' ? '' : demoNote}`
}

