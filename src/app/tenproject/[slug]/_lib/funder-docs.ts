export function brandHeader(ctx: ImpactPortalContext, docLabel: string) {
  return `<div class="brand">
    <img src="${ctx.brand.logo}" alt="${esc(ctx.brand.logoAlt)}">
    <div class="doc">${esc(docLabel)}<br>${new Date().toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric' })}</div>
  </div>`
}

const tiles = (items: { label: string; value: string | number }[]) =>
  `<div class="tiles">${items.map(t => `<div class="tile"><b>${esc(String(t.value))}</b><span>${esc(t.label)}</span></div>`).join('')}</div>`

// ─── 1. Term report (AI-drafted) ────────────────────────────────────────────
function termReport(ctx: ImpactPortalContext) {
  const { INSIGHTS, FUNNEL, SCHOOLS, IMPACT_AREAS } = ctx.data
  const b = ctx.brand
  const top3 = INSIGHTS.impactSurvey.slice(0, 3)
  const body = `
    ${brandHeader(ctx, ctx.copy.funder.termReportLabel)}
    <h1>${esc(b.org)} — Term Report</h1>
    <div class="sub">${esc(ctx.copy.funder.termReportSub)}</div>

    <h2>THE TERM IN NUMBERS</h2>
    ${tiles(INSIGHTS.headline)}

    <h2>NARRATIVE SUMMARY</h2>
    <p>This term ${b.org} reached ${INSIGHTS.headline[0]?.value} children each week in curriculum time across our partner schools, with an average attendance of ${INSIGHTS.headline[3]?.value} — every figure drawn from named-child digital registers rather than estimates. Weekend family sessions grew from ${INSIGHTS.weekendTrend[0]} family visits in week 1 to ${INSIGHTS.weekendTrend[INSIGHTS.weekendTrend.length - 1]} by week 10, as families reached in school converted to community participation.</p>
    <p>Of the ${FUNNEL[0]?.n} children reached in school this term, ${FUNNEL[1]?.n} families activated the parent app (${FUNNEL[1]?.pct}%), ${FUNNEL[3]?.n} attended a weekend community session (${FUNNEL[3]?.pct}%), and ${FUNNEL[4]?.n} became regular attendees. This school-to-community conversion is the programme's core outcome — school as the hub, family activity as the result.</p>

    <h2>SCHOOL BY SCHOOL</h2>
    <table><tr><th>School</th><th>Status</th><th>Children</th><th>Parent activation</th></tr>
    ${SCHOOLS.map(s => `<tr><td><b>${esc(s.name)}</b></td><td>${esc(s.status.toUpperCase())}</td><td>${s.children ?? '—'}</td><td>${s.activation ? s.activation + '%' : '—'}</td></tr>`).join('')}
    </table>

    <h2>WHAT FAMILIES TOLD US</h2>
    <p>Families surveyed cited the following areas of improvement: ${IMPACT_AREAS.join(', ')}. The three most-cited were ${top3.map((a, i) => `${i === 2 ? 'and ' : ''}${a.area} (${a.pct}%)`).join(', ').replace(', and', ' and')}.</p>

    <h2>SAFEGUARDING & COMPLIANCE</h2>
    <p>All delivering coaches hold current DBS checks, LTA Safeguarding & Protection training, First Aid certification and £5m insurance, tracked with automatic expiry alerts in the portal. Photography and data consent is recorded per family and enforced at every session.</p>

    <div class="foot">${esc(b.legal)} · ${esc(b.town)} · ${esc(b.domain)} · ${foot(ctx)}</div>
  `
  return shell(ctx, `${b.org} — Term Report`, body)
}

// ─── 2. Funder pack ─────────────────────────────────────────────────────────
