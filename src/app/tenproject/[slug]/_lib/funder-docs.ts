export function esc(s: string) {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
}

// Footer credit — live documents draw from real registers, so no demo note.
export function foot(ctx: ImpactPortalContext, demoNote = ' (demo data — live version draws from real registers)') {
  return `Generated by the ${ctx.brand.portal}${ctx.mode === 'live' ? '' : demoNote}`
}

