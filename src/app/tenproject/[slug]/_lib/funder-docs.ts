// ─── 5. Parent newsletter snippet (copyable) ────────────────────────────────
function newsletterSnippet(ctx: ImpactPortalContext) {
  const { SCHOOL_STATS, CAMPAIGN } = ctx.data
  const b = ctx.brand
  const text = ctx.copy.funder.snippetParas.map(p => fill(p, b, {
    term: SCHOOL_STATS.term.replace(' (completed)', ''),
    children: SCHOOL_STATS.headline[0]?.value ?? '',
    attendance: SCHOOL_STATS.headline[1]?.value ?? '',
    stickers: SCHOOL_STATS.headline[2]?.value ?? '',
    completed: SCHOOL_STATS.headline[3]?.value ?? '',
    raised: CAMPAIGN.raised.toLocaleString(),
    target: CAMPAIGN.target.toLocaleString(),
  })).join('\n')
  const body = `
    ${brandHeader(ctx, 'PARENT NEWSLETTER SNIPPET')}
    <h1>Parent newsletter snippet</h1>
    <div class="sub">Drop-in copy for the school newsletter or parent app — use the Copy text button above, then paste and edit freely</div>
    ${text.split('\n\n').map(p2 => `<p style="margin-bottom:12px; white-space: pre-line">${esc(p2)}</p>`).join('')}
    <div class="foot">${esc(b.legal)} · ${foot(ctx, ' (demo data)')}</div>
  `
  return shell(ctx, `${b.org} — Newsletter Snippet`, body, text)
}

export function openFunderDoc(kind: FunderDocKind, ctx: ImpactPortalContext) {
  const html =
    kind === 'term-report' ? termReport(ctx)
    : kind === 'funder-pack' ? funderPack(ctx)
    : kind === 'governor-pack' ? governorPack(ctx)
    : kind === 'newsletter-snippet' ? newsletterSnippet(ctx)
    : bidNarrative(ctx)
  openDocWindow(html)
}

export function openDocWindow(html: string) {
  const w = window.open('', '_blank')
  if (!w) return
  w.document.open()
  w.document.write(html)
  w.document.close()
}
